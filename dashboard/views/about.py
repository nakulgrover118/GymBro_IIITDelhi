with c1:
    st.markdown("""
#### How the twin works
1. **Prior from the EHR** – fasting glucose, fasting insulin (HOMA-IR / HOMA-B), weight, HbA1c, sulfonylurea use and
   TCF7L2 genotype set the patient's initial physiology.
2. **Nightly calibration** – a cross-entropy search re-learns insulin sensitivity, meal response, basal glucose and
   dawn effect from the previous day's CGM, regularised towards the EHR prior.
3. **Live synchronisation** – an observer nudges the twin to every CGM reading and estimates an unexplained
   "disturbance" input (unlogged snacks, stress hormones).
4. **Forecast** – from the synchronised state, the twin simulates 2 hours ahead using what was eaten/dosed plus the
   patient's learned routine.
5. **ML fusion layer** – LightGBM combines CGM history, EHR, wearables, logs and the twin's simulation into
   calibrated spike probabilities and 30/60/120-min forecasts with conformal 80% intervals.
6. **Explain** – exact TreeSHAP contributions become plain-language reasons.
""")
with c2:
    st.markdown("""
#### Data (sandbox rules)
* **Synthetic Indian cohort** – 200 virtual patients × 14 days generated by our Synthea-style Python generator
  (ICMR-INDIAB-informed distributions, regional Indian diets, FHIR R4 export). No real person is represented.
* **ShanghaiT2DM** (Zhao et al., *Scientific Data* 2023, CC BY 4.0) – 100 real, anonymised people with T2D and
  15-minute CGM, used to validate the pipeline on real-world signals.
* No identifiable data is collected or stored; the design follows the DPDP Act 2023 principles of purpose limitation
  and data minimisation.

#### Limitations
* Research prototype – **not a medical device**; must not be used for treatment decisions.
* Wearable–glucose relationships in the synthetic cohort come from published effect sizes, not measured data.
* ShanghaiT2DM has no wearable data and free-text diet logs (carbs are estimated).
* Next steps: prospective validation with Indian CGM users (e.g. via an institutional ethics committee),
  federated learning across hospitals, ABDM/FHIR integration.
""")
