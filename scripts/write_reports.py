"""Step 5: write docs/results.md (full result tables) from artifacts/results/*.csv."""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import pandas as pd  # noqa: E402

from glucotwin import config as C  # noqa: E402

LABEL = {"synthetic": "Synthetic Indian cohort (EHR + CGM + wearables + logs)",
         "shanghai": "Real-world ShanghaiT2DM (EHR summary + CGM + meal/insulin logs)"}


def md(df: pd.DataFrame) -> str:
    cols = list(df.columns)
    out = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for r in df.itertuples(index=False):
        out.append("| " + " | ".join(str(v) for v in r) + " |")
    return "\n".join(out)


def section(cohort: str) -> str:
    R = C.RESULTS_DIR
    res = json.loads((R / f"{cohort}_results.json").read_text())
    clf = pd.read_csv(R / f"{cohort}_classification.csv")
    ev = pd.read_csv(R / f"{cohort}_events.csv")
    reg = pd.read_csv(R / f"{cohort}_regression.csv")
    tr = pd.read_csv(R / f"{cohort}_alert_tradeoff.csv")
    st = pd.read_csv(R / f"{cohort}_shap_streams.csv")
    p = res["patients"]
    who = (f"{p['train']} train / {p['val']} validation / {p['test']} test patients" if "train" in p
           else f"{p['people']} people, {p['total_recordings']} recordings")
    s = [f"## {LABEL[cohort]}", "", f"*Evaluation: {res['evaluation']} ({who}); {res['rows_evaluated']:,} time points, "
         f"one every {res['step_min']} min.*", ""]
    c = clf[["model", "prevalence", "auroc", "auprc", "sensitivity", "specificity", "ppv"]].copy()
    c.columns = ["Model", "Spike prevalence", "AUROC", "AUPRC", "Sensitivity", "Specificity", "PPV"]
    for k in c.columns[1:]:
        c[k] = c[k].map(lambda v: f"{v:.3f}")
    s += ["### Spike prediction (new glucose > 180 mg/dL within 2 h, from below 180)", "", md(c), ""]
    e = ev[["model", "events", "event_recall", "median_lead_min", "alerts_per_day", "false_alerts_per_day"]].copy()
    e.columns = ["Model", "Spike events", "Flagged >= 15 min ahead", "Median warning (min)", "Alerts / patient-day",
                 "False alerts / patient-day"]
    e["Flagged >= 15 min ahead"] = e["Flagged >= 15 min ahead"].map(lambda v: f"{v:.1%}")
    for k in ("Median warning (min)", "Alerts / patient-day", "False alerts / patient-day"):
        e[k] = e[k].map(lambda v: f"{v:.1f}")
    s += ["### Event-level alert quality (60-min snooze on repeat notifications)", "", md(e), ""]
    pv = reg.pivot_table(index="model", columns="horizon", values="rmse").round(1)
    m60 = reg[reg.horizon == 60].set_index("model")[["mard", "clarke_A", "clarke_AB"]].round(1)
    g = pv.join(m60).reset_index().sort_values(120, ascending=False)
    g.columns = ["Model", "RMSE 30 min", "RMSE 60 min", "RMSE 120 min", "MARD 60 min (%)", "Clarke A 60 min (%)",
                 "Clarke A+B 60 min (%)"]
    s += ["### Glucose forecasting (mg/dL)", "", md(g), ""]
    cov = ", ".join(f"{h} min: {v['test_coverage_80']:.1%}" for h, v in res["conformal"].items())
    s += [f"Split-conformal 80% prediction intervals, empirical coverage: {cov}.", ""]
    t = tr[["threshold", "event_recall", "median_lead_min", "false_alerts_per_day"]].copy()
    t.columns = ["Probability threshold", "Spikes flagged", "Median warning (min)", "False alerts / patient-day"]
    t["Probability threshold"] = t["Probability threshold"].map(lambda v: f"{v:.2f}")
    t["Spikes flagged"] = t["Spikes flagged"].map(lambda v: f"{v:.1%}")
    t["False alerts / patient-day"] = t["False alerts / patient-day"].map(lambda v: f"{v:.2f}")
    s += ["### Alert operating points (GlucoTwin)", "", md(t), ""]
    st.columns = ["Data stream", "Share of mean |SHAP|"]
    st["Share of mean |SHAP|"] = st["Share of mean |SHAP|"].map(lambda v: f"{v:.1%}")
    s += ["### Which data stream drives the spike predictions", "", md(st), ""]
    return "\n".join(s)


if __name__ == "__main__":
    parts = ["# GlucoTwin: full results", "",
             "Generated by `scripts/write_reports.py` from `artifacts/results/`. All metrics are measured on patients "
             "the models never saw during training.", ""]
    for cohort in ("synthetic", "shanghai"):
        if (C.RESULTS_DIR / f"{cohort}_results.json").exists():
            parts.append(section(cohort))
    tl = C.RESULTS_DIR / "twin_learning.csv"
    if tl.exists():
        t = pd.read_csv(tl)
        t = t.assign(si_corr=t.si_corr.round(3), si_err=t.si_err.round(1), gb_err=t.gb_err.round(1))
        t.columns = ["Monitoring day", "Corr(twin SI, true SI)", "Median SI error (%)", "Median basal-glucose error (mg/dL)"]
        parts += ["## Does the twin learn each patient's hidden physiology? (synthetic cohort)", "",
                  "Day 0 is the EHR-only prior; later days use the nightly calibration.", "", md(t), ""]
    (C.ROOT / "docs" / "results.md").write_text("\n".join(parts), encoding="utf-8")
    print("wrote docs/results.md")
